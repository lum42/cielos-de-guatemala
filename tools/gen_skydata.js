// usage: node gen_skydata.js <build dir> <out js>
const fs = require("fs"), path = require("path");
const b = process.argv[2];
const stars = fs.readFileSync(path.join(b, "stars.b64"), "utf8").trim();
const mw = fs.readFileSync(path.join(b, "mw.webp")).toString("base64");
const lines = fs.readFileSync(path.join(b, "lines.json"), "utf8").trim();
const out = `// ── SKY DATA (generated by tools/gen_skydata.js — do not edit) ─────────────────
// Stars ≤ mag 6 (d3-celestial / HYG), packed little-endian: uint16 ra×100, int16 dec×100, int8 mag×10, int8 B–V×10
const STARS_B64 = "${stars}";
// Milky Way brightness, equirectangular 0.25°/px, RA 0→360 left→right, Dec +90 top (from d3-celestial mw.json, J. R. Vieira outlines)
const MW_URI = "data:image/webp;base64,${mw}";
// Constellation stick figures: flat [ra×10, dec×10, ...] polylines
const CON_LINES = ${lines};
`;
fs.writeFileSync(process.argv[3], out);
console.log("skydata bytes", out.length);
